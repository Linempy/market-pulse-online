/**
 * Операторы сравнения дивидендной доходности акции с заданным значением.
 */
public enum PriceOperator {
    /** Больше или равно. */
    GE,
    /** Больше. */
    GT,
    /** Меньше или равно. */
    LE,
    /** Меньше. */
    LT,
    /** Равно. */
    EQ
}
